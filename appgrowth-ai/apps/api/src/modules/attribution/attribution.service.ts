import { Injectable, Logger } from '@nestjs/common';
import { AnalyticsProviderKind, AttributionType, InstallKind, Platform, Prisma } from '@prisma/client';
import { AuditService } from '../../common/audit.service';
import { CryptoService } from '../../common/crypto.service';
import { AppError, notFound } from '../../common/errors';
import { toMinor } from '../../common/money';
import { PrismaService } from '../../common/prisma.service';
import { StoreService } from '../store/store.service';

export interface IncomingEvent {
  event_id?: string; type: string; event_key?: string; platform?: string; device_id?: string; occurred_at: string; country?: string;
  media_source?: string; campaign_id?: string; is_reinstall?: boolean; value?: string | number; currency?: string; installs?: number; conversion_value?: number;
}
const INSTALL_TYPES = new Set(['install', 'reinstall']);
const AGGREGATE_TYPES = new Set(['skan_install', 'aak_install']);
const CATEGORY: Record<string, string> = { first_open: 'engagement', session: 'engagement', sign_up: 'registration', registration: 'registration', login: 'login', purchase: 'purchase', subscribe: 'subscription', subscription: 'subscription' };
const ORGANIC = /^(organic|none|\(direct\)|direct)$/i;
const SIG_TOLERANCE_SEC = 300;

/**
 * Attribution ingestion. Sources: signed webhooks (any MMP/SDK forwarding events) and pull adapters for AppsFlyer,
 * Adjust and GA4/Firebase. De-duplication: provider event id when present, otherwise a fingerprint of
 * (source, type, device, minute) — enforced by a unique index, so replays and overlapping pulls never double count.
 * iOS SKAdNetwork / AdAttributionKit postbacks are stored as AGGREGATE rows and never matched to users.
 */
@Injectable()
export class AttributionService {
  private log = new Logger('Attribution');
  constructor(private prisma: PrismaService, private crypto: CryptoService, private audit: AuditService, private store: StoreService) {}

  // ── Sources (per app) ──
  async sources(orgId: string, userId: string, applicationId: string) {
    return this.prisma.tenant(orgId, userId, async (tx) => (await tx.attributionSource.findMany({ where: { organizationId: orgId, applicationId } })).map((s) => ({ ...s, secretEnc: undefined, hasSecret: !!s.secretEnc, webhookUrl: `${process.env.PUBLIC_URL}/api/v1/ingest/${s.id}/events` })));
  }

  async upsertSource(orgId: string, userId: string, applicationId: string, provider: AnalyticsProviderKind, dto: { config: Record<string, string>; secret?: string; attributionWindowDays?: number }) {
    const app = await this.prisma.application.findFirst({ where: { id: applicationId, organizationId: orgId, deletedAt: null } });
    if (!app) throw notFound('Application');
    const required: Record<AnalyticsProviderKind, string[]> = { APPSFLYER: ['appId'], ADJUST: ['appToken'], GA4: ['propertyId'], FIREBASE: ['propertyId'] };
    for (const k of required[provider]) if (!dto.config[k]) throw new AppError(`${provider} needs “${k}”`, 400, 'config_required');
    // Webhook signing secret is always generated by us; provider API secret is optional (pull adapters).
    return this.prisma.tenant(orgId, userId, async (tx) => {
      const existing = await tx.attributionSource.findUnique({ where: { applicationId_provider: { applicationId, provider } } });
      const webhookSecret = existing ? null : this.crypto.token(32);
      const secrets = existing?.secretEnc ? (JSON.parse(this.crypto.decrypt(existing.secretEnc)) as { webhook: string; api?: string }) : { webhook: webhookSecret! };
      if (dto.secret !== undefined) secrets.api = dto.secret || undefined;
      const s = await tx.attributionSource.upsert({
        where: { applicationId_provider: { applicationId, provider } },
        create: { organizationId: orgId, applicationId, provider, config: dto.config, secretEnc: this.crypto.encrypt(JSON.stringify(secrets)), attributionWindowDays: dto.attributionWindowDays ?? 7, status: 'PENDING' },
        update: { config: dto.config, secretEnc: this.crypto.encrypt(JSON.stringify(secrets)), attributionWindowDays: dto.attributionWindowDays },
      });
      await this.audit.record({ organizationId: orgId, actorUserId: userId, actor: `user:${userId}`, action: 'attribution.source_saved', entityType: 'attribution_source', entityId: s.id, after: { provider, config: dto.config, apiSecret: dto.secret === undefined ? undefined : 'updated' } }, tx);
      return { id: s.id, provider, webhookUrl: `${process.env.PUBLIC_URL}/api/v1/ingest/${s.id}/events`, ...(webhookSecret ? { webhookSecret, note: 'Shown once. Sign each request body with HMAC-SHA256 using this secret.' } : {}) };
    });
  }

  async removeSource(orgId: string, userId: string, id: string) {
    await this.prisma.tenant(orgId, userId, async (tx) => {
      const r = await tx.attributionSource.deleteMany({ where: { id, organizationId: orgId } });
      if (!r.count) throw notFound('Source');
      await this.audit.record({ organizationId: orgId, actorUserId: userId, actor: `user:${userId}`, action: 'attribution.source_removed', entityType: 'attribution_source', entityId: id }, tx);
    });
  }

  // ── Webhook ingestion ──
  /** Verifies `X-AppGrowth-Signature: t=<unix>,v1=<hex hmac(secret, "<t>.<rawBody>")>` (timestamped to block replays). */
  async verifyAndIngest(sourceId: string, rawBody: Buffer | undefined, signature: string | undefined) {
    const src = await this.prisma.attributionSource.findUnique({ where: { id: sourceId } });
    if (!src || !src.secretEnc) throw new AppError('Unknown source', 404, 'not_found');
    const m = /t=(\d+),v1=([0-9a-f]{64})/.exec(signature ?? '');
    const valid = !!m && !!rawBody && Math.abs(Date.now() / 1000 - Number(m[1])) <= SIG_TOLERANCE_SEC
      && this.crypto.safeEqual(this.crypto.hmac((JSON.parse(this.crypto.decrypt(src.secretEnc)) as { webhook: string }).webhook, `${m[1]}.${rawBody.toString('utf8')}`), m[2]);
    if (!valid) {
      // Signature first: invalid requests are recorded (for security review) but never de-duplicated against or processed.
      await this.prisma.webhookEvent.create({ data: { organizationId: src.organizationId, providerKey: `ingest:${src.provider}`, externalId: `invalid:${this.crypto.token(12)}`, signatureValid: false, payload: { rejected: true, bytes: rawBody?.length ?? 0 } } });
      throw new AppError('Invalid or expired signature', 401, 'invalid_signature');
    }
    // Replay protection: an identical signed request (same timestamp and body) is accepted once.
    const externalId = `${sourceId}:${m![1]}:${this.crypto.sha256(rawBody!.toString('utf8')).slice(0, 32)}`;
    try {
      await this.prisma.webhookEvent.create({ data: { organizationId: src.organizationId, providerKey: `ingest:${src.provider}`, externalId, signatureValid: true, payload: { bytes: rawBody!.length } } });
    } catch (e) {
      if (e instanceof Prisma.PrismaClientKnownRequestError && e.code === 'P2002') return { accepted: 0, duplicates: 0, replay: true };
      throw e;
    }
    let body: { events?: IncomingEvent[] };
    try { body = JSON.parse(rawBody!.toString('utf8')); } catch { throw new AppError('Body must be JSON', 400, 'invalid_json'); }
    if (!Array.isArray(body.events) || body.events.length > 5000) throw new AppError('Send { "events": [...] } with at most 5000 events', 400, 'invalid_payload');
    const r = await this.ingest(src.organizationId, src.applicationId, src.provider.toLowerCase(), body.events);
    await this.prisma.attributionSource.update({ where: { id: src.id }, data: { status: 'CONNECTED', statusDetail: '', lastSyncedAt: new Date() } });
    await this.prisma.webhookEvent.updateMany({ where: { providerKey: `ingest:${src.provider}`, externalId }, data: { processedAt: new Date() } });
    return r;
  }

  /** Validates, normalises and stores events. Returns counts; invalid events are reported, not stored. */
  async ingest(orgId: string, applicationId: string, source: string, events: IncomingEvent[]) {
    const app = await this.prisma.application.findUniqueOrThrow({ where: { id: applicationId }, include: { platforms: true } });
    const campaigns = await this.prisma.campaign.findMany({ where: { organizationId: orgId, applicationId, externalCampaignId: { not: null } }, select: { id: true, externalCampaignId: true } });
    const campByExt = new Map(campaigns.map((c) => [c.externalCampaignId!, c.id]));
    const defaultPlatform = app.platforms.length === 1 ? app.platforms[0].platform : null;
    let installs = 0, conversions = 0, aggregates = 0, duplicates = 0; const errors: string[] = [];
    for (const [i, e] of events.entries()) {
      const at = new Date(e.occurred_at);
      if (!e.type || Number.isNaN(at.getTime()) || at.getTime() > Date.now() + 3_600_000) { errors.push(`#${i}: missing type or invalid occurred_at`); continue; }
      const platform = (e.platform?.toUpperCase() === 'IOS' ? 'IOS' : e.platform?.toUpperCase() === 'ANDROID' ? 'ANDROID' : defaultPlatform) as Platform | null;
      const country = /^[A-Za-z]{2}$/.test(e.country ?? '') ? e.country!.toUpperCase() : 'ZZ';
      const device = e.device_id ? this.crypto.deviceHash(e.device_id) : null;
      const campaignId = e.campaign_id ? campByExt.get(String(e.campaign_id)) ?? null : null;
      const minute = Math.floor(at.getTime() / 60_000);
      const dedupeKey = e.event_id ? `${source}:${String(e.event_id).slice(0, 200)}` : `${source}:fp:${this.crypto.sha256([e.type, e.event_key ?? '', device ?? '', minute, platform ?? '', e.campaign_id ?? ''].join('|')).slice(0, 40)}`;
      try {
        if (AGGREGATE_TYPES.has(e.type)) {
          const n = Math.max(0, Math.floor(Number(e.installs ?? 1)));
          await this.prisma.attributionEvent.create({ data: { organizationId: orgId, applicationId, source: e.type === 'skan_install' ? 'skadnetwork' : 'adattributionkit', granularity: 'AGGREGATE', dedupeKey, campaignId, externalCampaignId: e.campaign_id ?? null, country, date: new Date(Date.UTC(at.getUTCFullYear(), at.getUTCMonth(), at.getUTCDate())), installs: n, conversionValue: e.conversion_value ?? null } });
          aggregates++;
        } else if (INSTALL_TYPES.has(e.type)) {
          if (!platform) { errors.push(`#${i}: platform required (app has both platforms)`); continue; }
          let kind: InstallKind = e.type === 'reinstall' || e.is_reinstall ? 'REINSTALL' : 'FIRST_INSTALL';
          // A device that already installed this app is a reinstall, whatever the source says.
          if (kind === 'FIRST_INSTALL' && device && (await this.prisma.installEvent.count({ where: { applicationId, deviceIdHash: device, platform } }))) kind = 'REINSTALL';
          const attribution: AttributionType = campaignId || (e.media_source && !ORGANIC.test(e.media_source)) ? 'PAID' : e.media_source && ORGANIC.test(e.media_source) ? 'ORGANIC' : 'UNATTRIBUTED';
          await this.prisma.installEvent.create({ data: { organizationId: orgId, applicationId, platform, source, dedupeKey, deviceIdHash: device, kind, attribution, campaignId, externalCampaignId: e.campaign_id ?? null, mediaSource: e.media_source?.slice(0, 100) ?? null, country, installedAt: at } });
          installs++;
        } else {
          const key = (e.event_key ?? e.type).slice(0, 60);
          let valueMinor: bigint | null = null;
          if (e.value !== undefined && e.value !== null && e.value !== '') { try { valueMinor = toMinor(Number(e.value).toFixed(2)); } catch { valueMinor = null; } }
          await this.prisma.conversionEvent.create({ data: { organizationId: orgId, applicationId, eventKey: key, category: CATEGORY[e.type] ?? CATEGORY[key] ?? 'custom', platform, source, dedupeKey, deviceIdHash: device, campaignId, country, valueMinor, currency: e.currency?.toUpperCase().slice(0, 3) ?? null, occurredAt: at } });
          conversions++;
        }
      } catch (err) {
        if (err instanceof Prisma.PrismaClientKnownRequestError && err.code === 'P2002') duplicates++;
        else { errors.push(`#${i}: ${(err as Error).message.slice(0, 120)}`); }
      }
    }
    return { accepted: installs + conversions + aggregates, installs, conversions, aggregates, duplicates, rejected: errors.length, errors: errors.slice(0, 20) };
  }

  // ── Pull adapters ──
  async pull(sourceId: string, days = 3) {
    const src = await this.prisma.attributionSource.findUniqueOrThrow({ where: { id: sourceId } });
    const cfg = src.config as Record<string, string>;
    const secrets = src.secretEnc ? (JSON.parse(this.crypto.decrypt(src.secretEnc)) as { api?: string }) : {};
    const to = new Date(); const from = new Date(to.getTime() - days * 86_400_000);
    const d = (x: Date) => x.toISOString().slice(0, 10);
    try {
      let result: unknown;
      if (src.provider === 'APPSFLYER') {
        if (!secrets.api) throw new AppError('Add the AppsFlyer API token (V2) to pull raw installs', 400, 'secret_required');
        // Pull API raw-data export (user-level installs, CSV). Requires the customer's AppsFlyer plan to include raw data.
        const r = await fetch(`https://hq1.appsflyer.com/api/raw-data/export/app/${encodeURIComponent(cfg.appId)}/installs_report/v5?from=${d(from)}&to=${d(to)}&timezone=UTC`, { headers: { Authorization: `Bearer ${secrets.api}`, Accept: 'text/csv' }, signal: AbortSignal.timeout(120_000) });
        if (!r.ok) throw new AppError(`AppsFlyer ${r.status}: ${(await r.text()).slice(0, 200)}`, 502, 'provider_error');
        result = await this.ingest(src.organizationId, src.applicationId, 'appsflyer', parseAppsflyerCsv(await r.text()));
      } else if (src.provider === 'ADJUST') {
        if (!secrets.api) throw new AppError('Add the Adjust API token to pull reports', 400, 'secret_required');
        // Report Service API: aggregate installs per day/campaign/country — stored as aggregate rows (not user-level).
        const q = new URLSearchParams({ app_token__in: cfg.appToken, date_period: `${d(from)}:${d(to)}`, dimensions: 'day,campaign_id_network,country_code,os_name,network', metrics: 'installs,reattributions' });
        const r = await fetch(`https://automate.adjust.com/reports-service/report?${q}`, { headers: { Authorization: `Bearer ${secrets.api}` }, signal: AbortSignal.timeout(60_000) });
        if (!r.ok) throw new AppError(`Adjust ${r.status}: ${(await r.text()).slice(0, 200)}`, 502, 'provider_error');
        const rows = ((await r.json()) as { rows?: Record<string, string>[] }).rows ?? [];
        result = await this.storeAggregate(src.organizationId, src.applicationId, 'adjust', rows.map((x) => ({ date: x.day, campaign: x.campaign_id_network, country: x.country_code, installs: Number(x.installs ?? 0), platform: x.os_name, network: x.network })));
      } else {
        // GA4 Data API (Firebase Analytics data lives in its GA4 property): first_open events by date/source/country/OS.
        if (!secrets.api) throw new AppError('Add a Google service account JSON with Viewer access to the GA4 property', 400, 'secret_required');
        const token = await this.store.googleServiceToken(secrets.api, 'https://www.googleapis.com/auth/analytics.readonly');
        const r = await fetch(`https://analyticsdata.googleapis.com/v1beta/properties/${encodeURIComponent(cfg.propertyId)}:runReport`, {
          method: 'POST', headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' }, signal: AbortSignal.timeout(60_000),
          body: JSON.stringify({ dateRanges: [{ startDate: d(from), endDate: d(to) }], dimensions: [{ name: 'date' }, { name: 'firstUserSource' }, { name: 'countryId' }, { name: 'operatingSystem' }, { name: 'firstUserCampaignId' }], metrics: [{ name: 'eventCount' }], dimensionFilter: { filter: { fieldName: 'eventName', stringFilter: { value: 'first_open' } } }, limit: 100000 }),
        });
        if (!r.ok) throw new AppError(`GA4 ${r.status}: ${(await r.text()).slice(0, 200)}`, 502, 'provider_error');
        const rows = ((await r.json()) as { rows?: { dimensionValues: { value: string }[]; metricValues: { value: string }[] }[] }).rows ?? [];
        result = await this.storeAggregate(src.organizationId, src.applicationId, src.provider.toLowerCase(), rows.map((x) => { const v = x.dimensionValues.map((y) => y.value); return { date: `${v[0].slice(0, 4)}-${v[0].slice(4, 6)}-${v[0].slice(6, 8)}`, network: v[1], country: v[2], platform: v[3], campaign: v[4], installs: Number(x.metricValues[0].value) }; }));
      }
      await this.prisma.attributionSource.update({ where: { id: src.id }, data: { status: 'CONNECTED', statusDetail: '', lastSyncedAt: new Date() } });
      return result;
    } catch (e) {
      await this.prisma.attributionSource.update({ where: { id: src.id }, data: { status: 'ERROR', statusDetail: (e as Error).message.slice(0, 300) } });
      throw e;
    }
  }

  /** Aggregate (non user-level) counts. Stored once per (source, day, campaign, country, os, network) — re-pulls replace. */
  private async storeAggregate(orgId: string, applicationId: string, source: string, rows: { date: string; campaign?: string; country?: string; installs: number; platform?: string; network?: string }[]) {
    const campaigns = await this.prisma.campaign.findMany({ where: { organizationId: orgId, applicationId, externalCampaignId: { not: null } }, select: { id: true, externalCampaignId: true } });
    const byExt = new Map(campaigns.map((c) => [c.externalCampaignId!, c.id]));
    let n = 0;
    for (const r of rows) {
      if (!/^\d{4}-\d{2}-\d{2}$/.test(r.date) || !Number.isFinite(r.installs)) continue;
      const country = /^[A-Za-z]{2}$/.test(r.country ?? '') ? r.country!.toUpperCase() : 'ZZ';
      const dedupeKey = `${source}:agg:${r.date}:${r.campaign ?? ''}:${country}:${r.platform ?? ''}:${r.network ?? ''}`.slice(0, 250);
      const data = { installs: Math.round(r.installs), raw: { network: r.network, platform: r.platform } as Prisma.InputJsonValue, campaignId: r.campaign ? byExt.get(r.campaign) ?? null : null, externalCampaignId: r.campaign || null };
      await this.prisma.attributionEvent.upsert({ where: { applicationId_dedupeKey: { applicationId, dedupeKey } }, create: { organizationId: orgId, applicationId, source, granularity: 'AGGREGATE', dedupeKey, country, date: new Date(`${r.date}T00:00:00Z`), ...data }, update: data });
      n++;
    }
    return { aggregates: n };
  }
}

/** Minimal RFC-4180 CSV parser for the AppsFlyer raw installs report. */
export function parseAppsflyerCsv(csv: string): IncomingEvent[] {
  const rows: string[][] = []; let row: string[] = []; let cell = ''; let q = false;
  for (let i = 0; i < csv.length; i++) {
    const ch = csv[i];
    if (q) { if (ch === '"') { if (csv[i + 1] === '"') { cell += '"'; i++; } else q = false; } else cell += ch; }
    else if (ch === '"') q = true;
    else if (ch === ',') { row.push(cell); cell = ''; }
    else if (ch === '\n' || ch === '\r') { if (ch === '\r' && csv[i + 1] === '\n') i++; row.push(cell); rows.push(row); row = []; cell = ''; }
    else cell += ch;
  }
  if (cell || row.length) { row.push(cell); rows.push(row); }
  const [head, ...data] = rows.filter((r) => r.length > 1);
  if (!head) return [];
  const idx = (n: string) => head.findIndex((h) => h.trim().toLowerCase() === n.toLowerCase());
  const I = { id: idx('AppsFlyer ID'), time: idx('Install Time'), media: idx('Media Source'), camp: idx('Campaign ID'), country: idx('Country Code'), platform: idx('Platform'), event: idx('Event Name') };
  return data.map((r) => ({
    event_id: `${r[I.id]}:${r[I.time]}`, type: 'install', device_id: r[I.id], occurred_at: (r[I.time] ?? '').replace(' ', 'T') + 'Z',
    media_source: r[I.media], campaign_id: I.camp >= 0 ? r[I.camp] || undefined : undefined, country: r[I.country], platform: r[I.platform],
  }));
}
