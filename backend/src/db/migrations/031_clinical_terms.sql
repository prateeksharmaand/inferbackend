-- Symptom & diagnosis master data for InferPad.
-- emr_clinical_terms: shared terms (clinic_id NULL) + each clinic's own terms.
-- emr_clinical_term_clinic: per-clinic state for any term (hidden, usage count) — lets a clinic
--   hide shared terms and ranks its most-used terms first.
-- Seeded from emr-web/src/data/templateSuggestions.js (InferPad's specialty quick-add lists).
-- ICD-10-CM codes are set only where the term maps cleanly to one code; edit in Settings.

CREATE TABLE IF NOT EXISTS emr_clinical_terms (
  id          SERIAL PRIMARY KEY,
  clinic_id   INTEGER REFERENCES emr_clinics(id) ON DELETE CASCADE,  -- NULL = shared
  kind        VARCHAR(20) NOT NULL CHECK (kind IN ('symptom', 'diagnosis')),
  name        TEXT        NOT NULL,
  icd10_code  VARCHAR(20),
  specialties TEXT[]      NOT NULL DEFAULT '{}',
  sort_rank   INTEGER     NOT NULL DEFAULT 100,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_clinical_terms_scope_kind_name
  ON emr_clinical_terms (COALESCE(clinic_id, 0), kind, LOWER(name));
CREATE INDEX IF NOT EXISTS idx_clinical_terms_kind ON emr_clinical_terms (kind, clinic_id);
CREATE INDEX IF NOT EXISTS idx_clinical_terms_specialties ON emr_clinical_terms USING GIN (specialties);

CREATE TABLE IF NOT EXISTS emr_clinical_term_clinic (
  clinic_id    INTEGER NOT NULL REFERENCES emr_clinics(id) ON DELETE CASCADE,
  term_id      INTEGER NOT NULL REFERENCES emr_clinical_terms(id) ON DELETE CASCADE,
  hidden       BOOLEAN NOT NULL DEFAULT FALSE,
  usage_count  INTEGER NOT NULL DEFAULT 0,
  last_used_at TIMESTAMPTZ,
  PRIMARY KEY (clinic_id, term_id)
);

